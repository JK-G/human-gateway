def one_line(text):
    return " ".join(str(text).split())


def cell(text):
    return one_line(text).replace("|", "\\|")


def reason(item, t):
    if item["why"] == "source_stale":
        return t["source_stale"] % int(item.get("days") or 0)
    return t.get(item["why"], item["why"])


def changes(items, t):
    return ", ".join("`%s` (%s)" % (c["path"], reason(c, t)) for c in items)


def gate_link(gate_id, title):
    """The title is committed text: escaped, it stays the words of one link and cannot close it or add its own."""
    return "[%s](gates/%s.md)" % (re.sub(r"([\\\[\]()<>])", r"\\\1", one_line(title)), gate_id)


def waits(data, t):
    lines = ["- %s: %s: %s" % (t["reopened"], gate_link(g["id"], g["title"]), changes(g["changed"], t))
             for g in data["gates"] if g["status"] == "reopened"]
    lines += ["- %s: %s: %s" % (t["source_check"], gate_link(g["id"], g["title"]), changes(g["changed"], t))
              for g in data["gates"] if g["status"] == "unchecked"]
    lines += ['- %s: %s, %s: "%s"' % (t["agent"] if a["own"] else t["agent_other"] % one_line(a["by"]),
                                      gate_link(a["gate"], a["title"]), a["at"][:10], one_line(a["request"]))
              for a in data["agent_approvals"]]
    lines += ["- %s (%s): %s" % (t["question"], q["project"], one_line(q["text"])) for q in data["open_questions"]]
    return lines or [t["nothing"]]


def gates_table(data, t):
    if not data["gates"]:
        return [t["no_gates"]]
    names = {"draft": t["draft"], "approved": t["approved"], "reopened": t["reopened_status"],
             "unchecked": t["unchecked_status"]}
    rows = ["| %s | %s | %s | %s |" % (t["gate"], t["status"], t["accountable_column"], t["changes"]), "|---|---|---|---|"]
    rows += ["| %s | %s | %s | %s |" % (cell(gate_link(g["id"], g["title"])), names[g["status"]], cell(g["accountable"]),
                                        cell(changes(g["changed"], t)))
             for g in data["gates"]]
    return rows


def project_lines(root, conf, t):
    vault = conf["VAULT_DIR"].rstrip("/")
    lines = []
    for slug in kr.projects(conf):
        page = "%s/projects/%s/CLAUDE.md" % (vault, slug)
        lines.append("- [%s](%s)" % (slug, page if (root / page).is_file() else "%s/projects/%s/" % (vault, slug)))
    return lines or [t["no_projects"]]


def activity_lines(root, conf, today, t):
    since = (datetime.date.fromisoformat(today) - datetime.timedelta(days=ACTIVITY_DAYS - 1)).isoformat()
    folder = root / conf["JOURNAL_DIR"]
    lines = []
    for path in sorted(folder.glob("*.md")) if folder.is_dir() else []:
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", path.stem) and since <= path.stem <= today:
            text = path.read_text(encoding="utf-8", errors="replace")
            lines.append("- %s: %d" % (path.stem, sum(1 for ln in text.splitlines() if ln.startswith("- "))))
    return [t["sessions"], ""] + lines if lines else [t["no_activity"]]


def render(root, conf, data):
    t = TEXT["pl" if gate_tool.is_polish(conf) else "en"]
    parts = ["# %s" % one_line(conf["KIT_PROJECT_NAME"]), "", "_%s_" % t["generated"]]
    sections = ((t["waits"], waits(data, t)), (t["gates"], gates_table(data, t)),
                (t["projects"], project_lines(root, conf, t)),
                (t["activity"], activity_lines(root, conf, data["date"], t)))
    for heading, lines in sections:
        parts += ["", "## %s" % heading, ""] + lines
    return "\n".join(parts) + "\n"


def refresh():
    root = kr.kit_root().resolve()
    conf = kr.load_conf(root)
    text = render(root, conf, today_data.collect(root))
    target = root / "DASHBOARD.md"
    if target.is_file() and target.read_bytes() == text.encode("utf-8"):
        return
    gate_tool.write_atomic(target, text)


def main():
    kr.stdio_utf8()
    sink = io.StringIO()
    try:
        with contextlib.redirect_stdout(sink), contextlib.redirect_stderr(sink):
            refresh()
    except Exception:  # a dashboard outage must never disturb the session
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
