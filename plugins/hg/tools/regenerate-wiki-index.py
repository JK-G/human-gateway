#!/usr/bin/env python3
"""regenerate-wiki-index.py - idempotent generator for the vault index files.

Writes, from page frontmatter only:
  <VAULT_DIR>/index.md          router: page counts by type and by project
  <VAULT_DIR>/index-<type>.md   one per registry type, pages grouped by project

Types come from the registry in vault/schema.md and projects from hg.json, both
through kit_registry.py. The output carries no timestamp, so an unchanged wiki
produces byte-identical files and the script does not touch them (no-op write).

Usage:
  regenerate-wiki-index.py [--root DIR]           rewrite stale index files
  regenerate-wiki-index.py [--root DIR] --check   exit 1 if any index file is stale
Exit: 0 ok / fresh, 1 stale (--check) or registry error, 2 usage error.
Stdlib only.
"""
import collections, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kit_registry as kr  # noqa: E402

HEADER = "_Generated by hg-tool index, do not hand-edit._"


def collect(root, conf, reg):
    pages, wiki = [], kr.wiki_dir(root, conf)
    for p in kr.iter_wiki_pages(root, conf):
        try:
            fm, _, _ = kr.parse_frontmatter(p)
        except kr.RegistryError:
            fm = None
        if not fm or fm.get("type") not in reg["types"]:
            continue
        summary = str(fm.get("summary") or "").replace("\n", " ").strip()
        if len(summary) > 160:
            summary = summary[:157].rstrip() + "..."
        pages.append({
            "type": fm["type"],
            "project": str(fm.get("project") or "cross"),
            "status": str(fm.get("status") or "active"),
            "temporal": str(fm.get("temporal") or ""),
            "slug": p.stem,
            "path": p.relative_to(wiki).as_posix(),
            "summary": summary,
        })
    return pages


def project_order(conf, present):
    order = kr.projects(conf) + ["cross"]
    return order + sorted(p for p in present if p not in order)


def _front(title):
    return ["---", "title: %s" % title, "type: index", "project: cross", "---", ""]


def render_router(conf, reg, pages):
    by_type = collections.Counter(p["type"] for p in pages)
    by_proj = collections.Counter(p["project"] for p in pages)
    vault = conf["VAULT_DIR"].rstrip("/") + "/"
    vrel = lambda key: conf[key][len(vault):] if conf[key].startswith(vault) else conf[key]
    out = _front("Wiki index") + ["# Wiki index", "", HEADER, "",
           "One knowledge base, organized by type; `project` is a frontmatter value. **%d pages.**" % len(pages),
           "", "## By type", ""]
    for t in reg["types"]:
        out.append("- **%s** (%d) -> [[index-%s]]" % (t, by_type.get(t, 0), t))
    out += ["", "## By project", ""]
    for pr in project_order(conf, by_proj):
        if by_proj.get(pr):
            out.append("- **%s**: %d" % (pr, by_proj[pr]))
    out += ["", "## Layers", "",
            "- `wiki/`: curated pages by type. Contract: [[schema]].",
            "- `raw/`: immutable sources per project (ingest-only).",
            "- `journal/`: append-only session journal, distilled into `wiki/memory/`.",
            "- `%s`: shared memory, loaded into every session." % vrel("MEMORY_INDEX"),
            "- `%s`: machine op log." % vrel("LOG_FILE"),
            "", "## Operations", "",
            "- `/hg:ingest <path>` \u00b7 `/hg:wiki-query \"<question>\"`",
            "- Regenerate: `hg-tool index`",
            "- Sub-indexes: one `index-<type>.md` per registry type, grouped by project.", ""]
    return "\n".join(out)


def render_type(conf, t, pages):
    rows = [p for p in pages if p["type"] == t]
    out = _front("Wiki index: %s" % t) + ["# Wiki index: %s (%d)" % (t, len(rows)), "", HEADER, "",
                                           "Back to [[index]].", ""]
    if not rows:
        out += ["_No pages of this type yet._", ""]
        return "\n".join(out)
    groups = collections.defaultdict(list)
    for p in rows:
        groups[p["project"]].append(p)
    for pr in project_order(conf, groups):
        items = groups.get(pr)
        if not items:
            continue
        out += ["## %s (%d)" % (pr, len(items)), ""]
        for p in sorted(items, key=lambda x: (x["status"] != "active", x["slug"])):
            flags = [] if p["status"] == "active" else [p["status"]]
            if p["temporal"] == "snapshot":
                flags.append("snapshot")
            tail = " (%s)" % ", ".join(flags) if flags else ""
            summ = ": %s" % p["summary"] if p["summary"] else ""
            out.append("- [[%s]]%s%s" % (p["slug"], tail, summ))
        out.append("")
    return "\n".join(out)


def main(argv):
    kr.stdio_utf8()
    args, root = list(argv), None
    if "--root" in args:
        k = args.index("--root")
        if k + 1 >= len(args):
            print(__doc__, file=sys.stderr)
            return 2
        root = args[k + 1]
        del args[k:k + 2]
    check = "--check" in args
    if [a for a in args if a != "--check"]:
        print(__doc__, file=sys.stderr)
        return 2
    root = kr.kit_root(root)
    conf = kr.load_conf(root)
    try:
        reg = kr.load_registry(root, conf)
    except kr.RegistryError as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        return 1
    pages = collect(root, conf, reg)
    vault = root / conf["VAULT_DIR"]
    wanted = {vault / "index.md": render_router(conf, reg, pages)}
    for t in reg["types"]:
        wanted[vault / ("index-%s.md" % t)] = render_type(conf, t, pages)
    stale = [p for p, txt in wanted.items() if not p.is_file() or p.read_text(encoding="utf-8") != txt]
    rel = lambda p: p.relative_to(root).as_posix()
    if check:
        for p in stale:
            print("WARN\t%s\tindex_stale: run hg-tool index" % rel(p))
        return 1 if stale else 0
    for p in stale:
        tmp = p.with_suffix(".md.tmp")
        with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(wanted[p])
        tmp.replace(p)
    print("index: %d pages, %d file(s) rewritten%s" % (
        len(pages), len(stale), (": " + ", ".join(rel(p) for p in stale)) if stale else " (no changes)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
